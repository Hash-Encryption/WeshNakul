function getCoords(placeId, fallbackLat, fallbackLng) {
  const item = existingCoords[placeId];
  if (item && item.lat && item.lng) {
    return { latitude: item.lat, longitude: item.lng };
  }
  return { latitude: fallbackLat ?? null, longitude: fallbackLng ?? null };
}

